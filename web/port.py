"""Builds the pygbag (browser) version of Asgard Defense into a folder.

web/src/ holds the Python 3 copies of asgard_defense.py and pyTreeBee.py made
with 2to3. This script takes them the rest of the way, without touching the
original code by hand:

- Python 2 division: `a / b` keeps truncating when both sides are integers;
- Windows paths ('Image\\x.png', 'Data\\game data.ages') become plain names,
  matching the files at the repository root, ignoring case;
- music and sounds point to .ogg copies (the workflow converts them with
  ffmpeg), since pygbag only packs .ogg sound;
- the pyTreeBee main loop becomes asynchronous, so the browser gets a frame
  after each pygame.display.update().

Usage: python web/port.py <output folder>
"""
import ast
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'web', 'src')
OUT = sys.argv[1]
ASSET_EXT = ('.png', '.jpg', '.wav', '.mp3', '.aiff', '.otf', '.ttf', '.ogg')
TO_OGG = ('.mp3', '.aiff', '.wav')
ROOT_FILES = {n.lower(): n for n in os.listdir(ROOT) if os.path.isfile(os.path.join(ROOT, n))}
used = set()


class Py2Division(ast.NodeTransformer):
    def visit_BinOp(self, node):
        self.generic_visit(node)
        if isinstance(node.op, ast.Div):
            return ast.copy_location(ast.Call(ast.Name('__py2div__', ast.Load()), [node.left, node.right], []), node)
        return node

    def visit_AugAssign(self, node):
        self.generic_visit(node)
        if isinstance(node.op, ast.Div):
            load = ast.parse(ast.unparse(node.target), mode='eval').body
            call = ast.Call(ast.Name('__py2div__', ast.Load()), [load, node.value], [])
            return ast.copy_location(ast.Assign([node.target], call), node)
        return node


class Paths(ast.NodeTransformer):
    def visit_Constant(self, node):
        if not isinstance(node.value, str):
            return node
        s = node.value
        if s in ('Sound\\', 'Image\\', 'Font\\'):
            return ast.copy_location(ast.Constant(''), node)
        s = s.replace('\\', '/')
        if s.lower().endswith(ASSET_EXT):
            real = ROOT_FILES.get(s.lower())
            if real:
                used.add(real)
                s = real
            if s.lower().endswith(TO_OGG):
                s = os.path.splitext(s)[0] + '.ogg'
        return ast.copy_location(ast.Constant(s), node)


class AsyncLoop(ast.NodeTransformer):
    """pyTreeBee: treeBeeStart() and dynamicScreen.run() become coroutines."""

    def visit_FunctionDef(self, node):
        self.generic_visit(node)
        if node.name in ('treeBeeStart', 'run'):
            new = ast.AsyncFunctionDef(node.name, node.args, node.body, node.decorator_list, node.returns, node.type_comment)
            return ast.copy_location(new, node)
        return node

    def visit_Expr(self, node):
        self.generic_visit(node)
        call = node.value
        if isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute):
            f = call.func
            if f.attr == 'run' and not call.args:
                return ast.copy_location(ast.Expr(ast.Await(call)), node)
            if f.attr in ('update', 'flip') and ast.unparse(f.value) == 'pygame.display':
                pause = ast.parse('await asyncio.sleep(0)').body[0]
                return [node, pause]
        return node


PRELUDE = '''import asyncio
import builtins


def __py2div__(a, b):
    if isinstance(a, int) and isinstance(b, int):
        return a // b
    return a / b


builtins.__py2div__ = __py2div__
'''


def port(name, extra):
    tree = ast.parse(open(os.path.join(SRC, name), encoding='utf-8').read())
    tree = Paths().visit(Py2Division().visit(tree))
    tree = extra(tree)
    code = ast.unparse(ast.fix_missing_locations(tree))
    head = '# Generated by web/port.py from web/src/%s (see the docstring there).\n' % name
    return head + PRELUDE + code + '\n'


def tree_bee(tree):
    return AsyncLoop().visit(tree)


def asgard(tree):
    # everything from the call that starts the screens on runs inside main()
    start = next(i for i, n in enumerate(tree.body)
                 if 'treeBeeStart' in ast.unparse(n))
    tail = tree.body[start:]
    for i, n in enumerate(tail):
        if isinstance(n, ast.Expr) and 'treeBeeStart' in ast.unparse(n):
            tail[i] = ast.copy_location(ast.Expr(ast.Await(n.value)), n)
    names = sorted({m.id for n in tail for m in ast.walk(n) if isinstance(m, ast.Name) and isinstance(m.ctx, ast.Store)})
    body = ([ast.Global(names)] if names else []) + tail
    for i, n in enumerate(list(body)):
        if isinstance(n, ast.Expr) and isinstance(n.value, ast.Call) and ast.unparse(n.value.func) == 'pygame.display.update':
            body.insert(i + 1, ast.parse('await asyncio.sleep(0)').body[0])
    main = ast.AsyncFunctionDef('main', ast.arguments([], [], None, [], [], None, []), body, [], None, None)
    tree.body = tree.body[:start] + [main, ast.parse('asyncio.run(main())').body[0]]
    return tree


os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, 'main.py'), 'w', encoding='utf-8').write(port('asgard_defense.py', asgard))
open(os.path.join(OUT, 'pyTreeBee.py'), 'w', encoding='utf-8').write(port('pyTreeBee.py', tree_bee))
for real in sorted(used):
    src = os.path.join(ROOT, real)
    if real.lower().endswith(TO_OGG):
        open(os.path.join(OUT, 'to-ogg.txt'), 'a').write(real + '\n')
    else:
        shutil.copy(src, os.path.join(OUT, real))
shutil.copytree(os.path.join(ROOT, 'Data'), os.path.join(OUT, 'Data'), dirs_exist_ok=True)
print('assets:', len(used))
